export function magnitudeTier(magnitude: number): "low" | "moderate" | "high" | "severe" {
  if (magnitude < 3.5) return "low";
  if (magnitude < 4.5) return "moderate";
  if (magnitude < 6) return "high";
  return "severe";
}


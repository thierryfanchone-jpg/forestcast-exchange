import type { EarthquakeEvent, SourceHealth } from "@/lib/types/earthquake";

// Données de démonstration réalistes (coordonnées et localités réelles),
// magnitudes/horodatages simulés en attendant la connexion aux flux temps réel.

type Seed = Omit<EarthquakeEvent, "id" | "confidence" | "confidenceScore"> & {
  confidence?: EarthquakeEvent["confidence"];
};

function confidenceFor(score: number): EarthquakeEvent["confidence"] {
  if (score >= 0.85) return "verified";
  if (score >= 0.6) return "likely";
  return "unconfirmed";
}

function build(seeds: Seed[]): EarthquakeEvent[] {
  return seeds.map((seed, index) => {
    const confidenceScore = Math.min(
      0.99,
      0.55 + seed.magnitude / 12 + (seed.source === "USGS" || seed.source === "EMSC" ? 0.08 : 0),
    );
    return {
      ...seed,
      id: `pc-${seed.source.toLowerCase()}-${index}-${seed.externalId}`,
      confidence: seed.confidence ?? confidenceFor(confidenceScore),
      confidenceScore: Number(confidenceScore.toFixed(2)),
    };
  });
}

const NOW = new Date("2026-07-02T14:00:00Z");
function hoursAgo(h: number) {
  return new Date(NOW.getTime() - h * 3600 * 1000).toISOString();
}
function daysAgo(d: number) {
  return new Date(NOW.getTime() - d * 24 * 3600 * 1000).toISOString();
}
function yearsAgo(y: number, monthDay = "01-15T10:00:00Z") {
  return new Date(NOW.getFullYear() - y, 0, 1).toISOString().slice(0, 4) + `-${monthDay}`;
}

